const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('map_component/index.html','utf8');
const code=html.split('<script>')[1].split('</script>')[0];
const sent=[],updates=[],handlers=[];let loads=0;
const parent={postMessage(value){sent.push(value);}};
const child={postMessage(value){updates.push(value);}};
const frame={contentWindow:child,set srcdoc(value){loads++;this.html=value;}};
const window={addEventListener(name,handler){handlers.push(handler);}};
vm.runInNewContext(code,{parent,window,document:{getElementById(){return frame;}}});
const render=args=>handlers[0]({source:parent,data:{type:'streamlit:render',args}});
render({html:'first-map',navigation:'dong-a',regions:[],explore:null});
assert.equal(loads,1);
render({html:'new-colors',navigation:'dong-a',regions:[{code:'b'}],explore:{}});
assert.equal(loads,1,'자료 갱신으로 지도 프레임을 재생성하면 안 됨');
assert.equal(updates.at(-1).type,'zipchack:data');
handlers[0]({source:child,data:{type:'zipchack:viewport',viewport:{south:37.5,west:127,north:37.6,east:127.1}}});
assert.equal(sent.at(-1).type,'streamlit:setComponentValue');
assert.equal(sent.at(-1).value.west,127);
const before=sent.length;
handlers[0]({source:{},data:{type:'zipchack:viewport',viewport:{}}});assert.equal(sent.length,before);
render({html:'new-location',navigation:'dong-b',regions:[],explore:null});assert.equal(loads,2);
